import { execFileSync } from "node:child_process";
import path from "node:path";
import vtkXMLImageDataReader from "@kitware/vtk.js/IO/XML/XMLImageDataReader";
import vtkXMLPolyDataReader from "@kitware/vtk.js/IO/XML/XMLPolyDataReader";
import { describe, expect, it } from "vitest";

function runPythonExport(script: string): ArrayBuffer {
  const repoRoot = path.resolve(__dirname, "../../..");
  const pythonExe = path.join(repoRoot, ".venv", "Scripts", "python.exe");
  const b64 = execFileSync(pythonExe, ["-c", script], {
    cwd: repoRoot,
    encoding: "utf-8",
    maxBuffer: 25 * 1024 * 1024,
  }).trim();
  const buf = Buffer.from(b64, "base64");
  return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
}

describe("Cross-stack VTK XML binary compatibility (Python -> @kitware/vtk.js)", () => {
  it("parses FEM surface .vtp generated by vtk_xml.py with all PointData arrays", () => {
    const ab = runPythonExport(`
import base64
import numpy as np
from tests.fixtures_stl import make_cube_stl_bytes
from topo_logic.domain.geometry import ElementType
from topo_logic.infrastructure.exporters.vtk_xml import export_fem_surface_vtp
from topo_logic.infrastructure.mesh import VoxelH8Mesher, deserialize_volume_mesh

stl = make_cube_stl_bytes(10.0, binary=True)
_, payload = VoxelH8Mesher().generate_volume_mesh(
    stl, geometry_id="test", element_type=ElementType.H8, target_element_size=5.0
)
mesh = deserialize_volume_mesh(payload)
n = len(mesh.nodes)
fields = {
    "displacement": np.ones((n, 3), dtype=np.float32) * 0.125,
    "displacement_magnitude": np.full(n, 0.2165, dtype=np.float32),
    "von_mises": np.linspace(10.0, 90.0, n, dtype=np.float32),
    "safety_factor": np.full(n, 2.5, dtype=np.float32),
}
print(base64.b64encode(export_fem_surface_vtp(mesh, fields)).decode("ascii"))
`);

    const reader = vtkXMLPolyDataReader.newInstance();
    const ok = reader.parseAsArrayBuffer(ab);
    expect(ok).toBe(true);

    const polyData = reader.getOutputData(0);
    expect(polyData.getNumberOfPoints()).toBe(26);
    expect(polyData.getNumberOfPolys()).toBe(48);

    const pointData = polyData.getPointData();
    const vm = pointData.getArrayByName("von_mises");
    const disp = pointData.getArrayByName("displacement");
    const sf = pointData.getArrayByName("safety_factor");

    expect(vm).toBeTruthy();
    expect(vm.getNumberOfTuples()).toBe(26);
    const vmData = vm.getData() as Float32Array;
    expect(Math.max(...vmData)).toBeCloseTo(90.0, 2);

    expect(disp.getNumberOfComponents()).toBe(3);
    expect(disp.getData()[0]).toBeCloseTo(0.125, 4);
    expect(sf.getData()[0]).toBeCloseTo(2.5, 4);
  });

  it("parses TopOpt 3D density .vti with 1-voxel zero halo in Fortran order", () => {
    const ab = runPythonExport(`
import base64, io
import numpy as np
from tests.fixtures_stl import make_cube_stl_bytes
from topo_logic.domain.geometry import ElementType
from topo_logic.infrastructure.exporters.vtk_xml import export_topopt_densities_vti
from topo_logic.infrastructure.mesh import VoxelH8Mesher, deserialize_volume_mesh

stl = make_cube_stl_bytes(10.0, binary=True)
_, payload = VoxelH8Mesher().generate_volume_mesh(
    stl, geometry_id="test", element_type=ElementType.H8, target_element_size=5.0
)
mesh = deserialize_volume_mesh(payload)
buf = io.BytesIO()
np.savez_compressed(
    buf,
    densities_phys=np.full(len(mesh.elements), 0.85, dtype=np.float32),
    densities_raw=np.full(len(mesh.elements), 0.85, dtype=np.float32),
    voxel_shape=np.asarray(mesh.voxel_shape, dtype=np.int32),
    voxel_origin=np.asarray(mesh.voxel_origin, dtype=np.float64),
    voxel_pitch=np.asarray(mesh.voxel_pitch, dtype=np.float64),
    active_voxel_ijk=np.asarray(mesh.active_voxel_ijk, dtype=np.int32),
)
print(base64.b64encode(export_topopt_densities_vti(buf.getvalue())).decode("ascii"))
`);

    const reader = vtkXMLImageDataReader.newInstance();
    const ok = reader.parseAsArrayBuffer(ab);
    expect(ok).toBe(true);

    const img = reader.getOutputData(0);
    expect(img.getDimensions()).toEqual([4, 4, 4]);
    expect(img.getSpacing()).toEqual([5, 5, 5]);
    const scalars = img.getPointData().getScalars().getData() as Float32Array;
    expect(scalars.length).toBe(64);
    expect(scalars[0]).toBe(0);
    // Index (1,1,1) in Fortran order (nx=4, ny=4): 1 + 4*1 + 16*1 = 21
    expect(scalars[21]).toBeCloseTo(0.85, 5);
  });
});
